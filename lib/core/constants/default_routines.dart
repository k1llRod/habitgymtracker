  static String getDayKeyForDateTime(DateTime dt, {bool fridayOptB = false}) {
    switch (dt.weekday) {
      case DateTime.monday:
        return 'lunes';
      case DateTime.tuesday:
        return 'martes';
      case DateTime.wednesday:
        return 'miercoles';
      case DateTime.thursday:
        return 'jueves';
      case DateTime.friday:
        return fridayOptB ? 'viernes_b' : 'viernes_a';
      default:
        return 'lunes'; // default fallback for weekend review or planning
    }
  }
